"""
tab_datasets.tex (booktabs) and fig_stats.pdf (single column) from stats.py's numbers.
Tumour share of tissue = annotated tumour area / tissue area per sample (slide; SICAPv2: overlap region), mean and
range over the samples that contain annotated tumour (most PANDA slides with ISUP 0 have none; their count is given).
"""
import sys as _sys
from pathlib import Path as _Path
_sys.path[:0] = [str(_Path(__file__).resolve().parents[1])] + [str(_Path(__file__).resolve().parents[1] / _d) for _d in ('data', 'train', 'eval', 'figures')]
import siteshift_paths as P

import numpy as np
import pandas as pd

from common import COL_W, FIGS, OI, plt, style

TYPE_COL = {"biopsy": OI["blue"], "large": OI["orange"]}
TYPE_NAME = {"biopsy": "Needle biopsies", "large": "Large sections"}


def share(x):
    t = x[x > 0]
    return f"{100 * t.mean():.0f}\\% ({100 * t.min():.1f}--{100 * t.max():.0f}\\%)", f"{len(t):,}/{len(x):,}"


def table():
    s = pd.read_csv(FIGS / "data" / "ours_slides.csv")
    pub = pd.read_csv(FIGS / "data" / "public_samples.csv")
    rows = []
    for label, d in [("Ours (all)", s), ("\\quad needle biopsies", s[s.type == "biopsy"]), ("\\quad large sections", s[s.type == "large"])]:
        sh, n = share(d.tumour_share)
        rows.append([label, f"{d.p.nunique()}", f"{len(d)}", f"{d.tiles.sum():,}",
                     {"Ours (all)": "biopsies + large sections", "\\quad needle biopsies": "needle biopsies",
                      "\\quad large sections": "large sections"}[label], "0.50", "whole-tumour region", sh, n])
    meta = {"SICAPv2": ("95$^a$", "155$^a$", "needle biopsies", "$\\approx$0.9$^b$", "gland-level Gleason"),
            "PANDA-Karolinska": ("n/a$^c$", None, "needle biopsies", "0.45 / 0.50$^g$", "coarse region"),
            "PANDA-Radboud": ("n/a$^c$", None, "needle biopsies", "0.49", "gland-level Gleason")}
    for name, (pts, slides, spec, um, ann) in meta.items():
        d = pub[pub.dataset == name]
        sh, n = share(d.tumour_share)
        nsamp = slides if slides else f"{len(d):,}"
        if name == "SICAPv2":
            n = f"{(d.tumour_share > 0).sum()}/{len(d)} regions$^d$"
        if name == "PANDA-Radboud":
            nsamp += "$^e$"
        rows.append([name, pts, nsamp, f"{d.tiles.sum():,}", spec, um, ann, sh, n])
    head = ["Dataset", "Patients", "Slides", "Tiles used", "Specimens", "\\textmu m/px", "Annotation",
            "Tumour share of tissue$^f$", "Samples with tumour"]
    tex = ["% generated by paper_figs/src/tab_and_stats.py", "\\begin{table*}[t]", "\\centering", "\\small",
           "\\setlength{\\tabcolsep}{4pt}", "\\begin{tabular}{lrrrllllr}", "\\toprule", " & ".join(head) + " \\\\", "\\midrule"]
    for i, r in enumerate(rows):
        tex.append(" & ".join(r) + " \\\\")
        if i == 2:
            tex.append("\\midrule")
    tex += ["\\bottomrule", "\\end{tabular}",
            "\\caption{Datasets. Tiles are 512\\,px. $^a$As reported by the SICAPv2 authors; the copy used has no slide "
            "identifiers. $^b$Nominal 10$\\times$ ($\\approx$1\\,\\textmu m/px); nuclei are 1.5--2$\\times$ smaller in pixels "
            "than ours, so its tiles are enlarged 1.75$\\times$ for training. $^c$PANDA releases no patient identifiers. "
            "$^d$Overlap regions reconstructed from the 50\\%-overlapping patches (238). $^e$The 2,100-slide subset used "
            "in the experiments (all 5,060 slides with masks: 784,351 tiles). $^g$Two scanners: 3,263 slides at 0.452 (Hamamatsu), 2,193 at 0.503\\,\\textmu m/px (Aperio). $^f$Annotated tumour area over tissue area "
            "per sample; mean (range) over samples with tumour.}",
            "\\label{tab:datasets}", "\\end{table*}"]
    (FIGS / "tab_datasets.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")
    print("\n".join(tex))


def figure():
    style()
    s = pd.read_csv(FIGS / "data" / "ours_slides.csv")
    reg = pd.read_csv(FIGS / "data" / "ours_regions.csv")
    p = s.groupby("p").agg(type=("type", "first"), tiles=("tiles", "sum"), tumour=("tumour_mm2", "sum"), tissue=("tissue_mm2", "sum"))
    p["share"] = (p.tumour / p.tissue).clip(upper=1)
    fig = plt.figure(figsize=(COL_W, 2.9))
    gs = fig.add_gridspec(2, 2, height_ratios=[1, 0.9], hspace=0.62, wspace=0.42, left=0.14, right=0.98, top=0.93, bottom=0.12)
    rng = np.random.default_rng(0)
    # a: tumour share per patient
    ax = fig.add_subplot(gs[0, 0])
    for i, typ in enumerate(["biopsy", "large"]):
        v = p[p.type == typ].share * 100
        ax.boxplot(v, positions=[i], widths=0.55, showfliers=False, medianprops=dict(color="black", lw=0.8),
                   boxprops=dict(lw=0.6), whiskerprops=dict(lw=0.6), capprops=dict(lw=0.6))
        ax.scatter(i + rng.uniform(-0.18, 0.18, len(v)), v, s=6, color=TYPE_COL[typ], alpha=0.85, lw=0, zorder=3)
    ax.set_xticks([0, 1], ["Biopsies\n(n=%d)" % (p.type == "biopsy").sum(), "Large sect.\n(n=%d)" % (p.type == "large").sum()])
    ax.set_ylabel("Tumour share of tissue (%)")
    ax.set_title("a  Tumour per patient", loc="left", fontsize=8)
    ax.spines[["top", "right"]].set_visible(False)
    # b: region sizes
    ax = fig.add_subplot(gs[0, 1])
    bins = np.logspace(np.log10(max(reg.area_mm2.min(), 1e-3)), np.log10(reg.area_mm2.max()), 25)
    for typ in ["biopsy", "large"]:
        ax.hist(reg[reg.type == typ].area_mm2, bins=bins, histtype="step", lw=1.0, color=TYPE_COL[typ],
                label=f"{'Biopsies' if typ == 'biopsy' else 'Large sect.'} ({(reg.type == typ).sum():,})")
    ax.set_xscale("log")
    ax.set_xlabel("Region area (mm$^2$)")
    ax.set_ylabel("Annotated regions")
    ax.set_ylim(0, ax.get_ylim()[1] * 1.45)
    ax.legend(frameon=False, fontsize=6, loc="upper left", handlelength=1.2, borderaxespad=0.1)
    ax.set_title("b  Region sizes", loc="left", fontsize=8)
    ax.spines[["top", "right"]].set_visible(False)
    # c: tiles per patient
    ax = fig.add_subplot(gs[1, :])
    q = p.sort_values(["type", "tiles"], ascending=[True, False])
    ax.bar(np.arange(len(q)), q.tiles, color=[TYPE_COL[t] for t in q.type], width=0.8)
    ax.set_yscale("log")
    ax.set_xticks([])
    ax.set_xlabel("Patients (sorted within specimen type)")
    ax.set_ylabel("Tiles")
    ax.set_xlim(-0.8, len(q) - 0.2)
    from matplotlib.patches import Patch
    ax.legend(handles=[Patch(color=TYPE_COL[t], label=TYPE_NAME[t]) for t in ["biopsy", "large"]],
              frameon=False, fontsize=6, ncol=1, loc="upper left", borderaxespad=0.1)
    ax.set_ylim(top=q.tiles.max() * 6)
    ax.set_title("c  Tiles per patient", loc="left", fontsize=8)
    ax.spines[["top", "right"]].set_visible(False)
    fig.savefig(FIGS / "fig_stats.pdf")
    fig.savefig(FIGS / "data" / "preview_fig_stats.png", dpi=200)
    print(f"regions: median {reg.area_mm2.median():.3f} mm2; per type:",
          reg.groupby("type").area_mm2.describe()[["count", "50%", "max"]].round(3).to_dict())
    print(p.groupby("type")[["share", "tiles"]].describe().round(3).T)


if __name__ == "__main__":
    table()
    figure()
